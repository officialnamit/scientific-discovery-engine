"""
Real-LLM (Gemini) run of the EXISTING pipeline, written to a separate folder so
the deterministic mock-provider results are never touched.

    Part A  experiments/09_evaluation.py's real_llm(): Mode A (no context) vs
            Mode B (RAG/KG context) hypothesis generation on 3 benchmark datasets.
    Part B  experiments/08_physics_constrained_search.py's stages, unchanged,
            with OUT redirected: generation -> filters -> inverse PINN per
            candidate -> selection -> stability -> held-out/OOD -> oracle.

Output: results/evaluation/real_llm_gemini/
Requires GEMINI_API_KEY in the environment; refuses to fall back to the mock.

Run:
    python experiments/11_real_llm_gemini.py --config config.yaml [--stage generate|prepare|pinn|select|all] [--model ...]
"""

import argparse
import importlib.util
import json
import os
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from hypotheses.search import save_json
from llm import get_provider
from llm.gemini_provider import GeminiProvider

OUT = "results/evaluation/real_llm_gemini"
MOCK_PHASE6 = "results/phase6"


def _load_script(filename, name):
    spec = importlib.util.spec_from_file_location(name, os.path.join(ROOT, "experiments", filename))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _phase6_module():
    p6 = _load_script("08_physics_constrained_search.py", "phase6_search")
    p6.OUT = os.path.join(OUT, "phase6")
    p6.CAND_DIR = os.path.join(p6.OUT, "candidates")
    p6.MODEL_DIR = os.path.join(p6.OUT, "models")
    return p6


def stage_generate(cfg):
    ev = _load_script("09_evaluation.py", "phase7_evaluation")
    res = ev.real_llm(cfg, run_it=True)
    for r in res.get("results") or []:
        r["rag_changed_hypotheses"] = sorted(r["mode_a"]) != sorted(r["mode_b"])
        r["rag_changed_families"] = sorted(r["mode_a_families"]) != sorted(r["mode_b_families"])
    save_json(res, os.path.join(OUT, "hypothesis_generation.json"))
    print(json.dumps(res, indent=2))


def annotate_report():
    """08's report template hardcodes mock-provider caveats; mark this copy as a real-LLM run."""
    path = os.path.join(OUT, "phase6", "phase6_report.md")
    info = json.load(open(os.path.join(OUT, "run_info.json")))
    text = open(path).read()
    note = (f"> **Real-LLM run:** candidates H* were generated by `{info['provider']}` (model `{info['model']}`), "
            "not the mock. The template's mock-provider caveats below (\"canned\" proposals) do not apply to "
            "the H* candidates; K* candidates are still knowledge-graph templates.\n\n")
    if not text.startswith("> **Real-LLM run"):
        open(path, "w").write(note + text)


def compare_with_mock():
    def load(base):
        sel = json.load(open(os.path.join(base, "model_selection.json")))
        val = json.load(open(os.path.join(base, "pinn_validation.json")))
        ood = json.load(open(os.path.join(base, "ood_predictions.json")))
        gen = json.load(open(os.path.join(base, "generated_candidates.json")))
        s = sel["selected"]
        return {"provider": gen["provider"],
                "llm_candidates": [h["equation"] for h in gen["llm_candidates"]],
                "pool": {p["id"]: p["equation"] for p in gen["pool"]},
                "status": {c: r["status"] for c, r in val.items()},
                "passed_physics_validation": [c for c, r in val.items() if r["status"].startswith("supported")],
                "selected": s, "selected_equation": val[s]["equation"] if s else None,
                "params": val[s]["params"] if s else None,
                "heldout_val_rmse": ood["in_distribution_val_rmse_noisy_obs"],
                "ood_rmse_noisy_obs": ood["ood_rmse_noisy_obs_t_gt_cutoff"],
                "oracle": ood["oracle_benchmark_evaluation"]}
    out = {"mock": load(MOCK_PHASE6), "gemini": load(os.path.join(OUT, "phase6"))}
    save_json(out, os.path.join(OUT, "comparison_with_mock.json"))
    print(json.dumps(out, indent=2, default=float))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="config.yaml")
    ap.add_argument("--stage", default="all", choices=["generate", "prepare", "pinn", "select", "all"])
    ap.add_argument("--only", default=None, help="comma-separated candidate ids for --stage pinn")
    ap.add_argument("--model", default=None, help="override llm.model for this run only (config.yaml is not changed)")
    a = ap.parse_args()
    cfg = yaml.safe_load(open(a.config))
    cfg["llm"]["provider"] = "gemini"
    if a.model:
        cfg["llm"]["model"] = a.model

    if a.stage in ("generate", "prepare", "all"):
        if not os.environ.get("GEMINI_API_KEY"):
            raise SystemExit("GEMINI_API_KEY is not set; refusing to run a 'real-LLM' experiment on the mock provider.")
        provider = get_provider(cfg["llm"])
        assert isinstance(provider, GeminiProvider), provider
        print(f"Using {provider.name} model={provider.model}")
        save_json({"provider": provider.name, "model": provider.model}, os.path.join(OUT, "run_info.json"))

    p6 = _phase6_module()
    if a.stage in ("generate", "all"):
        stage_generate(cfg)
    if a.stage in ("prepare", "all"):
        p6.stage_prepare(cfg)
    if a.stage in ("pinn", "all"):
        p6.stage_pinn(cfg, set(a.only.split(",")) if a.only else None)
    if a.stage in ("select", "all"):
        p6.stage_select(cfg)
        annotate_report()
        compare_with_mock()


if __name__ == "__main__":
    main()
